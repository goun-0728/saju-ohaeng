function compute(o){
  const [y,m,d]=o.date.split('-').map(Number);
  let hh=12,mm=0;
  if(o.hasTime){[hh,mm]=o.time.split(':').map(Number)}
  const z=zoneInfo(y,m,d);
  const off=z.base+(o.hasTime?z.dst:0);
  const tLocal=Date.UTC(y,m-1,d,hh,mm);
  const msUT=tLocal-off*3600e3;
  const jd=msToJd(msUT);
  const lon=sunLon(jd);

  // 년·월 (절기)
  const mb=Math.floor(mod(lon-315,360)/30);
  let sy=y; if(m<=2&&mb>=10) sy=y-1;
  const yi=mod(sy-4,60), ys=yi%10, yb=yi%12;
  const ms=mod((ys%5)*2+2+mb,10), mbr=mod(mb+2,12);

  // 일·시 (지방 평균태양시)
  let msL, corrMin=0;
  if(!o.hasTime) msL=tLocal;
  else if(o.lng==null){msL=tLocal-z.dst*3600e3}
  else{msL=msUT+o.lng/15*3600e3;corrMin=Math.round((msL-(tLocal))/60e3)}
  const cd=new Date(msL), ch=cd.getUTCHours();
  let jdn=Math.floor(msL/864e5)+2440588;
  const late=o.hasTime&&ch>=23;
  if(late&&o.ja==='jo') jdn+=1;
  const di=mod(jdn+49,60), ds=di%10, db=di%12;
  let hour=null;
  if(o.hasTime){
    const hb=Math.floor((ch+1)/2)%12;
    const baseStem=(late&&o.ja==='ya')?(ds+1)%10:ds;
    hour={s:mod((baseStem%5)*2+hb,10),b:hb};
  }

  // 대운
  const fwd=((ys%2===0)===(o.g==='M'));
  const prevT=mod(15+30*Math.floor(mod(lon-15,360)/30),360), nextT=mod(prevT+30,360);
  const jPrev=findTerm(prevT,jd-15), jNext=findTerm(nextT,jd+15);
  const days=fwd?(jNext-jd):(jd-jPrev);
  const startYears=days/3, dsu=Math.max(1,Math.round(startYears));
  const mi=idx60(ms,mbr), dw=[];
  for(let i=1;i<=10;i++){const n=mod(mi+(fwd?i:-i),60);dw.push({s:n%10,b:n%12,age:dsu+10*(i-1),year:y+dsu+10*(i-1)})}
  const lmt=o.hasTime?`${String(ch).padStart(2,'0')}:${String(cd.getUTCMinutes()).padStart(2,'0')}`:null;

  return {y,m,d,z,lmt,corrMin,lon,prevT,daysSince:jd-jPrev,
    pillars:{hour,day:{s:ds,b:db},month:{s:ms,b:mbr},year:{s:ys,b:yb}},dw,fwd,dsu,startYears,o};
}

